(int, int, int?)? rukuAt(int surahNumber, int verseNumber) {
  for (final row in _rukuSpans) {
    if (row.$1 == surahNumber && verseNumber >= row.$2 && verseNumber <= row.$3) {
      return (row.$4, row.$2, row.$3);
    }
  }
  return null;
}

bool isRukuEnd(int surahNumber, int verseNumber) =>
    rukuAt(surahNumber, verseNumber)?.$3 == verseNumber;
